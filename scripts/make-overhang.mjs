// Writes dist/data/overhang-levels.js: the Overhang levels with, for each, a
// shortest witness (from the exact solver) and the farthest its goal point
// can reach. node scripts/make-overhang.mjs
import {writeFileSync} from 'node:fs';
import {solveFrom, start, bestGoal, winners} from '../dist/phys/overhang.js';

// n blocks, all with right ends at `at` (0 is the table's edge), a flag at
// x = flag (in twelfths of a block), and optionally a marked block (counted
// from the bottom, 0) that must reach the flag instead of the whole stack.
const LEVELS = [
  // Easy: share the reach between two, then three blocks.
  {id: 'two-7', tier: 'easy', n: 2, at: 0, flag: 7},
  {id: 'two-9', tier: 'easy', n: 2, at: 0, flag: 9},
  {id: 'three-9', tier: 'easy', n: 3, at: 0, flag: 9},
  {id: 'three-10', tier: 'easy', n: 3, at: 0, flag: 10},
  // Medium: as far as three and four blocks go; a marked bottom block that
  // needs the top as a counterweight; a stack pushed out from the bottom
  // that has to come back before it can go out.
  {id: 'three-11', tier: 'medium', n: 3, at: 0, flag: 11},
  {id: 'two-star', tier: 'medium', n: 2, at: 0, flag: 9, mark: 0},
  {id: 'four-11', tier: 'medium', n: 4, at: 0, flag: 11},
  {id: 'four-pushed', tier: 'medium', n: 4, at: 6, flag: 12},
  {id: 'four-12', tier: 'medium', n: 4, at: 0, flag: 12},
  // Hard: a block wholly past the table; marked middle blocks held down by
  // one or two blocks above them as counterweights (three-star has exactly
  // one answer, and five-star's block reaches as far as any five can); six
  // blocks starting well back on the table.
  {id: 'five-13', tier: 'hard', n: 5, at: 0, flag: 13},
  {id: 'three-star', tier: 'hard', n: 3, at: 0, flag: 11, mark: 1},
  {id: 'four-star', tier: 'hard', n: 4, at: 0, flag: 11, mark: 1},
  {id: 'five-star', tier: 'hard', n: 5, at: 0, flag: 13, mark: 3},
  {id: 'six-back', tier: 'hard', n: 6, at: -6, flag: 14},
];

const out = LEVELS.map(level => {
  const witness = solveFrom(level, start(level), winners(level), 1e6);
  if (!witness) throw new Error(`${level.id}: no way to the flag`);
  return {...level, best: bestGoal(level), ways: winners(level).length, witness};
});
const text = `// Generated by scripts/make-overhang.mjs: do not edit by hand.
// Each level: n blocks with right ends at \`at\` (twelfths of a block; 0 is the
// table's edge), a flag at x = flag, an optional marked block (from the bottom)
// that must reach it, the farthest the goal point can reach (\`best\`), how
// many standing stacks win (\`ways\`), and a shortest witness: moves
// [block, +1 right or -1 left], each leaving the stack standing.
export default [
${out.map(l => '  ' + JSON.stringify(l)).join(',\n')},
];
`;
writeFileSync(new URL('../dist/data/overhang-levels.js', import.meta.url), text);
for (const l of out) console.log(l.id.padEnd(12), l.tier.padEnd(6), `n=${l.n} at=${l.at} flag=${l.flag} mark=${l.mark ?? '-'} best=${l.best} ways=${l.ways} moves=${l.witness.length}`, l.witness.map(([k, d]) => k + (d > 0 ? '+' : '-')).join(''));
